export async function seedCatalog() {
  const existingProducts = await db.product.findMany({ select: { name: true } });
  const existingNames = new Set(existingProducts.map((product) => product.name));
  let seeded = 0;

  for (const p of PRODUCTS) {
    if (existingNames.has(p.name)) continue;

    const product = await db.product.create({
      data: {
        name: p.name,
        brand: p.brand,
        category: p.category,
        subcategory: p.subcategory,
        specs: JSON.stringify(p.specs),
        basePrice: p.basePrice,
        rating: p.rating,
        reviewCount: p.reviewCount,
        imageUrl: (p as any).imageUrl,
        imageColor: p.imageColor,
        pros: JSON.stringify(p.pros),
        cons: JSON.stringify(p.cons),
        sentimentScore: p.sentimentScore,
        tags: JSON.stringify(p.tags),
        platformPrices: {
          create: p.platforms,
        },
      },
    });

    // Generate mock price history (last 8 weeks, weekly snapshots)
    const now = new Date();
    for (const pp of p.platforms) {
      for (let week = 8; week >= 0; week--) {
        const date = new Date(now.getTime() - week * 7 * 24 * 60 * 60 * 1000);
        // simulate small fluctuations
        const variance = (Math.sin(week * 0.7) + Math.random() * 0.5 - 0.25) * 0.08;
        const histPrice = Math.round(pp.price * (1 + variance));
        await db.priceHistory.create({
          data: {
            productId: product.id,
            platform: pp.platform,
            price: histPrice,
            recordedAt: date,
          },
        });
      }
    }
    seeded += 1;
  }

  return { seeded, skipped: seeded === 0, count: existingProducts.length + seeded };
}

export const PRODUCT_CATALOG_SIZE = PRODUCTS.length;
